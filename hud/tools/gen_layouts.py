def segs(fill_id: str, count: int, indent: str) -> str:
    seg = "".join(f'<Panel class="seg" hittest="false" />' for _ in range(count))
    return (f'{indent}<Panel class="segs segs-track" hittest="false">{seg}</Panel>\n'
            f'{indent}<Panel id="{fill_id}" class="segs segs-fill" hittest="false">{seg}</Panel>\n')


# ---------------------------------------------------------------------------------------------- shared stylesheet

def shared_css() -> str:
    out = ["""/*
    ranks_shared - generated by hud/tools/gen_layouts.py, do not edit by hand.

    Rank art and the bar ladder, shared by ranks_panel, ranks_feed and ranks_menu. The server cannot send an image
    path or a width, only a class, so every option is listed here: sg-0..sg-23 for the art (CS2's own skillgroup0-18
    plus the workshop addon's 19-23, at the same path) and p0..p50 for a bar, 2% a step.

    The bar is a clip, not a width. Writing any text in the same panel tree re-lays the row out and restarts a width
    transition from full; clip has no effect on layout, so it survives (runtime-behaviour.md, measured).
*/

.sg {
    background-size: 100% 100%;
    background-repeat: no-repeat;
    background-position: 50% 50%;
}
"""]
    for i in range(MAX_ICON + 1):
        out.append(f'.sg.sg-{i} {{ background-image: url("s2r://panorama/images/icons/skillgroups/skillgroup{i}.vsvg"); }}\n')

    out.append("""
/* Segments: a row of equal panels with a 3px gap. The fill row sits on top of the track row and is clipped. */
.segs {
    width: 100%;
    height: 100%;
    flow-children: right;
}
.seg {
    width: fill-parent-flow(1.0);
    height: 100%;
    margin-right: 3px;
    background-color: #ffffff17;
}
.seg:last-child { margin-right: 0px; }
.segs-fill .seg { background-color: #f0a531; }

.segs-fill {
    clip: rect( 0%, 0%, 100%, 0% );
    transition-property: clip;
    transition-duration: 0.6s;
    transition-timing-function: ease-out;
}
""")
    for i in range(STEPS + 1):
        out.append(f".segs-fill.p{i} {{ clip: rect( 0%, {i * 2}%, 100%, 0% ); }}\n")
    return "".join(out)


